
package condicionsimpleif;

public class CondicionSimpleIF {

    
    public static void main(String[] args) {
        //DEMOSTRAR MEDIANTE PANTALLA SI UN NUMERO ES MAYOR QUE OTRO

        int num1 = 15;
        int num2 = 10;

        if (num2 > num1) {
            //SI SE CUMPLE LA PRIMER CONDICION
            System.out.println("EL NUM2 ES MAYOR AL NUM1");
        } else {
            //SI NO SE CUMPLE LA PRIMER CONDICION
            System.out.println("EL NUM1 ES MAYOR AL NUM2");
        }
    }

}
